def hello_world():
    print("Hello, Again, World!!!") #prints hello world

def hello_you():
    name = input("Enter your name:") #prompts user to enter their name
    print("Hello,", name) #says hello to the user using their inputted name

def main():
    hello_world() #calls function hello_world()
    hello_you() #calls function hello_you() 

main()